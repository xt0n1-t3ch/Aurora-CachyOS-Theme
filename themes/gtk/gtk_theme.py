# Settings shared by GTK 3 and 4 (Plasma's GTK sync writes the same values from KDE's settings). Only these keys
# change; the rest of each settings.ini (modules, sounds, DPI) stays as Plasma wrote it.
SETTINGS = {
    "gtk-application-prefer-dark-theme": "true",
    "gtk-cursor-theme-name": "Aurora",
    "gtk-cursor-theme-size": "24",
    "gtk-decoration-layout": ":minimize,maximize,close",
    "gtk-font-name": f"{font},  10",
    "gtk-icon-theme-name": "Aurora-dark",
    "gtk-theme-name": "Aurora",
}


def merge_settings(path):
    """Sets the SETTINGS keys in the settings.ini at `path`, creating the file or its [Settings] line when missing.

    Other lines stay as they are; keys that were absent are appended at the end of the file.
    """
    lines = open(path).read().splitlines() if os.path.exists(path) else []
    if "[Settings]" not in (line.strip() for line in lines):
        lines.insert(0, "[Settings]")
    written = set()
    for i, line in enumerate(lines):
        key = line.split("=", 1)[0].strip()
        if "=" in line and key in SETTINGS:
            lines[i] = f"{key}={SETTINGS[key]}"
            written.add(key)
    lines += [f"{key}={value}" for key, value in SETTINGS.items() if key not in written]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


for directory in (gtk3, gtk4):
    merge_settings(os.path.join(directory, "settings.ini"))
print(f"GTK: Aurora + its window button capsule; {removed_rules} traffic-light rules replaced")
