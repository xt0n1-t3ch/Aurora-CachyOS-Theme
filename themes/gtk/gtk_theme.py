# The capsule, for libadwaita (GTK 4) and GTK 3 header bars.
def without_window_controls(css):
    """The theme's stylesheet minus its traffic-light rules. They hide the button icons with more specific
    selectors than a user sheet can safely match in every state, so the capsule rules below replace
    them instead of competing with them."""
    kept, removed, depth, start = [], 0, 0, 0
    i = 0
    while i < len(css):
        brace = css.find("{", i)
        if brace < 0:
            kept.append(css[i:])
            break
        selector = css[i:brace]
        if selector.strip().startswith("@"):
            # Keep @-blocks whole (media queries, keyframes); none of them hold window control rules.
            depth, j = 0, brace
            while j < len(css):
                depth += {"{": 1, "}": -1}.get(css[j], 0)
                j += 1
                if depth == 0:
                    break
            kept.append(css[i:j])
            i = j
            continue
        close = css.find("}", brace)
        rule = css[i:close + 1]
        if "windowcontrols" in selector:
            removed += 1
        else:
            kept.append(rule)
        i = close + 1
    return "".join(kept), removed

