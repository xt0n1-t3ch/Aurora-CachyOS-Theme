# The README's File Explorer pictures, on Dawn Bird (tests/helpers/showcase_wallpaper.sh): a Git repository with a
# file's Git menu open, the Commit sheet, the columns view, the gallery, the command palette, batch rename and the
# Inspector. Everything they show is made here in the sandbox's home, from Plasma's own wallpapers and a small made-up
# project. Captures go to shots/readme-fe-*.png; assets/screenshots/make.py crops them. Needs dolphin-plugins installed
# for the Git status, or AURORA_DOLPHIN_PLUGINS naming the root of its unpacked package (as explorer-git.sh).
source "$SBX/prelude.sh"
FI="$SB/tests/helpers/fakeinput/fakeinput"
SHOTS="$SBX/shots"
PLUGINS="${AURORA_DOLPHIN_PLUGINS:-}/usr/lib/qt6/plugins/dolphin/vcs"
if [ ! -e "$PLUGINS/fileviewgitplugin.so" ]; then
    echo "no Git plugin in $PLUGINS (install dolphin-plugins or set AURORA_DOLPHIN_PLUGINS)" > "$SBX/logs/readme-explorer.txt"
    exit 0
fi
if [ -n "${AURORA_DOLPHIN_PLUGINS:-}" ]; then
    mkdir -p "$HOME/.local/lib/qt6/plugins/dolphin/vcs"
    cp "$PLUGINS"/fileviewgitplugin.so "$HOME/.local/lib/qt6/plugins/dolphin/vcs/"
fi
kwriteconfig6 --file dolphinrc --group VersionControl --key enabledPlugins Git
kwriteconfig6 --file "$HOME/.local/share/file-explorer/view_properties/global/.directory" --group Settings --key HiddenFilesShown false
# The sandbox's home sits inside Aurora's own checkout; git must not look above it.
export GIT_CEILING_DIRECTORIES="$HOME"

PROJECT="$HOME/Projects/weather-station"
WALLPAPERS="$HOME/Pictures/Wallpapers"
TRIP="$HOME/Pictures/Lisbon"
rm -rf "$PROJECT" "$WALLPAPERS" "$TRIP" && mkdir -p "$PROJECT" "$WALLPAPERS" "$TRIP"
# The pictures are Plasma's wallpapers, made smaller so their previews come quickly.
python3 -I - "$WALLPAPERS" "$TRIP" <<'PY'
import os, sys
from PIL import Image
wallpapers, trip = sys.argv[1:3]
root = "/usr/share/wallpapers"
def picture(name):
    images = os.path.join(root, name, "contents/images")
    files = sorted(f for f in os.listdir(images) if f.endswith((".png", ".jpg")))
    image = Image.open(os.path.join(images, files[-1])).convert("RGB")
    image.thumbnail((1920, 1080))
    return image
for name in ["Abstract", "BlueFeathers", "DarkStreaks", "Dimensions", "Liquid", "Spectrum"]:
    picture(name).save(os.path.join(wallpapers, f"{name}.jpg"), quality=88)
for number, name in enumerate(["Lines", "Metal", "Skyscraper", "paper", "PurpleFeathers"], start=2041):
    picture(name).save(os.path.join(trip, f"img-{number}.jpg"), quality=88)
PY
printf 'Notes from the trip.\n' > "$TRIP/notes.txt"

# A small Rust project with work in progress: README.md and Cargo.toml changed, a sensor driver added and a wiring
# note not yet tracked.
(
    cd "$PROJECT" && git init -q -b main && git config user.name Sandbox && git config user.email sandbox@example.org
    mkdir -p src/sensors tests docs
    cat > Cargo.toml <<'EOF'
[package]
name = "weather-station"
version = "0.3.0"
edition = "2024"

[dependencies]
embedded-hal = "1.0"
EOF
    printf '# This file is automatically generated by Cargo.\nversion = 4\n' > Cargo.lock
    printf 'max_width = 120\n' > rustfmt.toml
    cat > README.md <<'EOF'
# Weather station

Reads temperature, humidity and pressure and shows them on a small display.
EOF
    cat > src/main.rs <<'EOF'
mod display;
mod sensors;

fn main() {
    let reading = sensors::bme280::read();
    display::show(&reading);
}
EOF
    printf 'pub fn show(reading: &crate::sensors::Reading) {\n    println!("{reading}");\n}\n' > src/display.rs
    printf 'pub mod bme280;\n\npub struct Reading {\n    pub celsius: f32,\n}\n' > src/sensors/mod.rs
    cat > src/sensors/bme280.rs <<'EOF'
use super::Reading;

/// Reads the BME280 once.
pub fn read() -> Reading {
    Reading { celsius: 21.5 }
}
EOF
    printf '#[test]\nfn reads() {}\n' > tests/readings.rs
    printf '# Calibration\n\nHold the sensor still for a minute.\n' > docs/calibration.md
    git add . && git commit -qm "Read the BME280 and show it"
    printf '\nRun it with cargo run --release.\n' >> README.md && git commit -qam "Say how to run it"
    git branch feature/history
    cat > src/sensors/bme280.rs <<'EOF'
use super::Reading;

/// How long the sensor needs after a forced measurement, in milliseconds.
const SETTLE_MS: u32 = 10;

/// Reads the BME280 once, waiting for the measurement to settle.
pub fn read() -> Reading {
    wait(SETTLE_MS);
    Reading { celsius: 21.5, humidity: 48.0, hectopascals: 1013.2 }
}
EOF
    printf 'pub fn read() -> super::Reading {\n    super::Reading { celsius: 22.0, humidity: 51.0, hectopascals: 0.0 }\n}\n' > src/sensors/dht22.rs
    git add src/sensors/dht22.rs
    sed -i 's/version = "0.3.0"/version = "0.4.0"/' Cargo.toml
    printf '\n## Sensors\n\nBME280 and DHT22, both on I2C.\n' >> README.md
    printf '# Wiring\n\nSDA to GPIO 2, SCL to GPIO 3.\n' > docs/wiring.md
)

input() { "$FI" "$@" > /dev/null 2>&1; }
type_word() {
    local -A code=([a]=30 [b]=48 [c]=46 [d]=32 [e]=18 [f]=33 [g]=34 [h]=35 [i]=23 [j]=36 [k]=37 [l]=38 [m]=50 [n]=49
                   [o]=24 [p]=25 [q]=16 [r]=19 [s]=31 [t]=20 [u]=22 [v]=47 [w]=17 [x]=45 [y]=21 [z]=44 [-]=12 [' ']=57)
    local word=$1 i
    for ((i = 0; i < ${#word}; i++)); do input keydown "${code[${word:i:1}]}" keyup "${code[${word:i:1}]}" wait 60; done
}
# palette WORD: opens the command palette (Ctrl+Shift+P) and types WORD.
palette() {
    input keydown 29 keydown 42 keydown 25 keyup 25 keyup 42 keyup 29 wait 600
    type_word "$1"
    input wait 400
}
# explorer FOLDER [xcb]: starts File Explorer on FOLDER in icons, as an X11 client with xcb, and sets FE to its PID.
explorer() {
    kwriteconfig6 --file file-explorerrc --group View --key Mode ""
    if [ "${2:-}" = xcb ]; then
        QT_QPA_PLATFORM=xcb "$SB/build/file-explorer/file-explorer" "$1" > "$SBX/logs/readme-fe.log" 2>&1 &
    else
        "$SB/build/file-explorer/file-explorer" "$1" > "$SBX/logs/readme-fe.log" 2>&1 &
    fi
    FE=$!
    waitfor 9
}
close_explorer() { kill "$FE"; waitfor 2; }

source "$SB/tests/helpers/showcase_wallpaper.sh"
plasmashell > "$SBX/logs/plasmashell.log" 2>&1 &
waitfor 12
showcase_wallpaper

# The project's Git status, and README.md's Git menu: the sixth item, a modified file. It comes first: after the other
# windows of this scenario the X11 window's menu did not open from scripted input.
explorer "$PROJECT" xcb
shot readme-fe-git-window
input move 1615 440 wait 200 rdown wait 80 rup wait 2000
shot readme-fe-git-menu
input glide 1660 924 10 wait 2500
shot readme-fe-git
input keydown 1 keyup 1 wait 300 keydown 1 keyup 1 wait 600
close_explorer

# The Inspector on a picture.
kwriteconfig6 --file file-explorerrc --group Inspector --key Visible true
explorer "$WALLPAPERS"
input move 900 454 wait 200 down wait 60 up wait 2500
shot readme-fe-inspector
close_explorer
kwriteconfig6 --file file-explorerrc --group Inspector --key Visible false

# The gallery, on the second picture.
explorer "$WALLPAPERS"
input move 1500 1000 wait 200 down wait 60 up wait 400
palette gallery
input keydown 28 keyup 28 wait 2000 keydown 29 keydown 30 keyup 30 keyup 29 wait 1500 keydown 106 keyup 106 wait 2500
shot readme-fe-gallery
close_explorer

# Batch rename: the five photos' img- becomes lisbon-; Escape leaves them as they are.
explorer "$TRIP"
input move 900 454 wait 200 down wait 80 up wait 300
input keydown 29 keydown 30 keyup 30 keyup 29 wait 300 keydown 60 keyup 60 wait 1500
type_word img-
input keydown 15 keyup 15 wait 200
type_word lisbon-
input wait 800
shot readme-fe-rename
input keydown 1 keyup 1 wait 500
close_explorer

# The command palette, finding the view commands.
explorer "$PROJECT"
input move 1500 1000 wait 200 down wait 60 up wait 400
palette view
shot readme-fe-palette
input keydown 1 keyup 1 wait 500
close_explorer

# The columns view, from Projects down to the sensors.
explorer "$PROJECT/src/sensors"
input move 1500 1000 wait 200 down wait 60 up wait 400
palette columns
input keydown 28 keyup 28 wait 3000
shot readme-fe-columns
close_explorer

# The Commit sheet, opened by fe-shots over the project.
mkdir -p "$SBX/run/readme-git"
"$SB/build/file-explorer/fe-shots" "$SBX/run/readme-git" "$PROJECT" git > "$SBX/logs/readme-fe-shots.log" 2>&1
mv "$SBX/run/readme-git/fe-git-commit.png" "$SHOTS/readme-fe-commit.png"
mv "$SBX/run/readme-git/fe-git-changes.png" "$SHOTS/readme-fe-changes.png"
kwriteconfig6 --file file-explorerrc --group View --key Mode ""
